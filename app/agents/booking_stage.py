booking_agent = create_react_agent(
    model=llm,
    tools=[
        get_categories_tool,
        get_services_tool,
        book_times_tool,
        find_slots_tool,
        create_booking_tool,
        call_manager_tool,
    ],
    prompt=BOOKING_STAGE_INSTRUCTION,
)

