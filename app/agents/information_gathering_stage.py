information_gathering_agent = create_react_agent(
    model=llm,
    tools=[
        get_categories_tool,
        get_services_tool,
        view_service_tool,
        about_salon_tool,
        masters_tool,
        call_manager_tool,
    ],
    prompt=INFORMATION_GATHERING_STAGE_INSTRUCTION,
)

